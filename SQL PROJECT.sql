USE online_food_delivery;
CREATE TABLE CUSTOMER
(CUSTOMER_ID INT PRIMARY KEY,
CUSTOMER_NAME VARCHAR (60),
EMAIL VARCHAR (60),
CITY VARCHAR (60),
SIGN_UP_DATE DATE);

CREATE TABLE RESTAURANT
(RESTAURANT_ID INT PRIMARY KEY,
RESTAURANT_NAMME VARCHAR (60),
CITY VARCHAR (60),
 REG_DATE DATE);
 
 
 CREATE TABLE MANU
 (ITEM_ID INT PRIMARY KEY,
 RESTAURANT_ID INT,
 ITEM_NAME VARCHAR (60),
 PRICE DECIMAL(10,2),
 CONSTRAINT FK_MANU_REST
 FOREIGN KEY (RESTAURANT_ID)
 REFERENCES RESTAURANT (RESTAURANT_ID)
 );

SELECT  ITEM_NAME,PRICE FROM MANU
WHERE PRICE>=300
ORDER BY PRICE DESC
LIMIT 5; 

SELECT COUNT(DISTINCT ITEM_NAME) AS UNIQUE_MANU FROM MANU;

