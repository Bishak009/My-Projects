DROP TABLE IF EXISTS ORDERS;

CREATE TABLE ORDERS
(ORDER_ID INT PRIMARY KEY,
CUSTOMER_ID INT,
RESTAURANT_ID INT,
ORDER_DATE DATE,
CONSTRAINT FK_NAME1 FOREIGN KEY(CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
CONSTRAINT FK_NAME2 FOREIGN KEY(RESTAURANT_ID) REFERENCES RESTAURANT(RESTAURANT_ID));

CREATE TABLE ORDERS_DETAILS
(ORDER_DETAIL_ID INT PRIMARY KEY,
ORDER_ID INT,
ITEM_ID INT,
QUANTITY INT,
CONSTRAINT FK_NAME3 FOREIGN KEY(ORDER_ID) REFERENCES ORDERS(ORDER_ID),
CONSTRAINT FK_NAME4 FOREIGN KEY(ITEM_ID) REFERENCES MANU(ITEM_ID));

SELECT CUSTOMER_NAME,COUNT(ORDER_ID) AS NUMBER_ORDERS
FROM CUSTOMER AS C JOIN ORDERS AS O 
ON C.CUSTOMER_ID=O.CUSTOMER_ID
GROUP BY CUSTOMER_NAME
ORDER BY NUMBER_ORDERS DESC;

SELECT COUNT(ORDER_DETAIL_ID),COUNT(ORDER_ID) FROM ORDERS_DETAILS;  

SELECT ITEM_NAME,COUNT(ORDER_DETAIL_ID) AS NUM_ORDERS FROM 
ORDERS_DETAILS AS OD LEFT JOIN MANU AS MU
ON OD.ITEM_ID=MU.ITEM_ID	
GROUP BY ITEM_NAME
ORDER BY NUM_ORDERS DESC;

SELECT ORDER_ID,SUM(PRICE) FROM 
ORDERS_DETAILS AS OD LEFT JOIN MANU AS MU
ON OD.ITEM_ID=MU.ITEM_ID	
GROUP BY ORDER_ID
ORDER BY SUM(PRICE) DESC
LIMIT 5;

SELECT CITY,SUM(PRICE*QUANTITY) AS TOTAL_REVENUE FROM
ORDERS_DETAILS AS OD LEFT JOIN MANU AS MU
ON OD.ITEM_ID=MU.ITEM_ID
JOIN RESTAURANT AS R ON 
 MU.RESTAURANT_ID = R.RESTAURANT_ID
 GROUP BY CITY;
 
 SELECT CITY,COUNT(ORDER_ID) AS TOTAL_ORDERS
 FROM RESTAURANT AS R JOIN ORDERS AS O ON
 R.RESTAURANT_ID = O.RESTAURANT_ID
 GROUP BY CITY
 HAVING TOTAL_ORDERS >5;
 
